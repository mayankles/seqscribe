#' Script builder
#'
#' Renders the completed steps into a standalone R script. The script sources
#' the project's own copies of the library functions, so it runs without the
#' app and is unaffected by later library edits.
#' @name script
#' @noRd
NULL

#' Code for one step
#' @noRd
step_code <- function(entry, params, produced) {
  args <- c(
    if (length(entry$inputs) > 0) paste0(entry$inputs, " = ", entry$inputs),
    if (length(params) > 0) paste0(names(params), " = ", vapply(params, deparse_value, ""))
  )
  lines <- paste0("out <- ", entry$name, "(", paste(args, collapse = ", "), ")")
  for (obj in produced) lines <- c(lines, paste0(obj, " <- out$objects$", obj))
  lines
}

#' Whole-project script
#' @noRd
build_script <- function(state) {
  if (length(state$steps) == 0) return("# No steps have been run yet.")
  fns <- unique(unlist(lapply(state$steps, function(s) if (!is_custom(s)) s$fn)))
  lines <- c(
    "# Generated by seqscribe. Run from the project folder.",
    paste0("# Workflow: ", state$workflow),
    "",
    "# Library functions used by this project (copies kept with the project)",
    paste0("source(file.path(\"scripts\", \"library\", \"", fns, ".R\"))"),
    ""
  )
  for (s in state$steps) {
    lines <- c(
      lines,
      if (is_custom(s)) {
        paste0("# ", s$id, ": custom code (not from the library)")
      } else {
        paste0("# ", s$id, ": ", s$title, "  [", s$fn, " v", s$version, "]")
      },
      s$code,
      ""
    )
  }
  lines
}

#' Is a step a custom code cell rather than a library call?
#' @noRd
is_custom <- function(step) identical(step$type, "custom")
